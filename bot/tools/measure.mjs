const rows = await p.evaluate((s) => [...document.querySelectorAll(s)].map((e) => { const r = e.getBoundingClientRect(); return `${(e.className || e.tagName).toString().slice(0, 28).padEnd(28)} y=${Math.round(r.top)} h=${Math.round(r.height)}`; }), sel);
