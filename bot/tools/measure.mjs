const [route, sel] = [process.argv[2] || '/', process.argv[3] || '.app > *'];
const BASE = 'http://localhost:3111'; const uid = 5555;
const hdr = { 'x-dev-user': String(uid), 'x-dev-username': 'YukeeDesign', 'Content-Type': 'application/json' };
