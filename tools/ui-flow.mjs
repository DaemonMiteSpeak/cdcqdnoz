// UI flow smoke test (DEV server on :3112 with SBP configured). node tools/ui-flow.mjs
process.env.DB_FILE = process.env.DB_FILE || '/tmp/e2e.db';
process.env.DEV = '1';
import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs';
const BASE = process.env.BASE || 'http://localhost:3112';
const S = await import('../src/service.js');
const uid = 880000 + Math.floor(Math.random() * 9999);
const hdr = { 'x-dev-user': String(uid), 'x-dev-username': 'FlowUser', 'Content-Type': 'application/json' };
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 360, height: 760 }, deviceScaleFactor: 2 })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/telegram|ERR_/.test(m.text())) errors.push(m.text()); });
const shot = (n) => page.screenshot({ path: `/tmp/flow/${n}.png` });
import fs from 'node:fs'; fs.mkdirSync('/tmp/flow', { recursive: true });
await page.request.get(`${BASE}/api/state`, { headers: hdr });
const wait = (ms) => page.waitForTimeout(ms);
await page.goto(`${BASE}/?dev=${uid}#/`);
await wait(800);
console.log('gate shown:', await page.locator('.gate-t').count() === 1);
await page.click('#chk'); await wait(600);
console.log('not-found note:', await page.locator('.note.bad').count() === 1);
await shot('1-gate-notfound');
await page.request.post(`${BASE}/api/dev/seed`, { headers: hdr, data: { gate_ok: 1 } });
await page.click('#chk'); await wait(600);
console.log('confirmed screen -> home auto (2.6s)'); await wait(3000);
console.log('home shown:', await page.locator('nav.nav').count() >= 1, page.url().split('#')[1]);
await shot('2-home');
await page.click('[data-go="/buy"]'); await wait(600);
await page.click('[data-plan="90"]'); await wait(500);
await shot('3-buy');
await page.click('#go'); await wait(600);
await shot('4-pay');
await page.click('[data-m="sbp"]'); await page.click('#go'); await wait(1200);
console.log('waiting screen:', await page.locator('#tm').count() === 1, page.url().split('#')[1]);
await shot('5-waiting');
const oid = Number(page.url().match(/order\/(\d+)/)[1]);
S.settleOrder(oid, { by: 'ui-test' });
await wait(5500);
console.log('success screen:', await page.locator('.res-t', { hasText: 'Оплата прошла' }).count() === 1);
await shot('6-success');
await page.goto(`${BASE}/?dev=${uid}#/launch`); await wait(700);
await page.click('#gen'); await wait(600);
await shot('7-launch');
await page.goto(`${BASE}/?dev=${uid}#/profile`); await wait(700);
await page.click('#reset'); await wait(400);
await shot('8-reset-confirm');
await page.click('#doreset'); await wait(600);
await shot('9-reset-done');
console.log('page errors:', errors.length ? errors : 'none');
await browser.close();
