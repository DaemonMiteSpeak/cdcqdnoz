// Hider relay: runs on the VPS.
//  - HTTPS+WSS control port: login (user key -> token), control WebSocket for the Hider desktop app.
//  - Per-session TCP listener (Minecraft clients connect here). Raw bytes are multiplexed over the
//    app's WebSocket, so the real game server only ever sees the user's own PC, never this VPS.
//  - Per-user logs are persisted in data/logs/<user>.jsonl.
const https = require('https');
const net = require('net');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { WebSocketServer } = require('ws');
const sec = require('./secure');

const ROOT = __dirname;
const DATA = process.env.HIDER_DATA || path.join(ROOT, 'data');
fs.mkdirSync(path.join(DATA, 'logs'), { recursive: true });

const CFG = Object.assign({
  controlPort: 50001,
  portMin: 50100,
  portMax: 50299,
  publicHost: '2c83be5612a6.hosting.myjino.ru',
  maxConnsPerSession: 12,
  graceMs: 120000,
  tokenTtlDays: 60,
  tokenTtlHours: 48,       // short-lived resume token; a fresh one is issued on every connect
  revalidateMs: 300000,    // re-check every logged-in app against users.json (expiry/revocation)
  hwidStrict: true,
  versions: ['26.2', '26.1', '1.21.11', '1.21.8', '1.21.4', '1.16.5'],
  labelTag: 'wtf',          // text of the in-game "[tag]" shown in front of Hider users
  debugLabelAll: true       // DEBUG: also label every non-Hider player so the feature can be verified
}, readJson(path.join(DATA, 'config.json'), {}));

function readJson(f, def) { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return def; } }
function writeJson(f, v) { fs.writeFileSync(f + '.tmp', JSON.stringify(v, null, 2)); fs.renameSync(f + '.tmp', f); }

// Protocol ID maps for versions newer than the bundled minecraft-data (26.2).
// Shipped with the relay and delivered to authenticated clients inside the sealed hello,
// so the desktop app no longer carries them on disk (can't speak 26.2 without the server).
const PROTO_PATCHES = readJson(path.join(ROOT, 'protocol-patches.json'), readJson(path.join(DATA, 'protocol-patches.json'), {}));

// AES-256-GCM key for the encrypted desktop engine (the app's src/engine.bin). Delivered to
// authenticated clients inside the sealed hello, so the app can't decrypt or run its engine offline.
const ENGINE_KEY = (() => {
  for (const f of [path.join(DATA, 'engine.key'), path.join(ROOT, 'engine.key')]) {
    try { const k = fs.readFileSync(f, 'utf8').trim(); if (/^[0-9a-f]{64}$/i.test(k)) return k; } catch { /* try next */ }
  }
  return '';
})();
if (!ENGINE_KEY) console.warn('[relay] WARNING: data/engine.key missing or invalid - the desktop engine will not unlock');

// Cosmetic assets (catalog + per-item rig/texture), delivered to authenticated subscribers at
// runtime so the models are not shipped inside the desktop app. Generated by tools/pack-cosmetics.js.
const COS_ASSETS = (() => {
  for (const f of [path.join(DATA, 'cosmetics-assets.json'), path.join(ROOT, 'cosmetics-assets.json')]) {
    try { const j = JSON.parse(fs.readFileSync(f, 'utf8')); if (j && j.catalog && j.items) return j; } catch { /* try next */ }
  }
  return null;
})();
if (!COS_ASSETS) console.warn('[relay] WARNING: cosmetics-assets.json missing - cosmetics will be unavailable to clients');

/* ---------- users / tokens ---------- */
const USERS_FILE = path.join(DATA, 'users.json');
const SECRET_FILE = path.join(DATA, 'secret.key');
if (!fs.existsSync(SECRET_FILE)) fs.writeFileSync(SECRET_FILE, crypto.randomBytes(32).toString('hex'), { mode: 0o600 });
const SECRET = Buffer.from(fs.readFileSync(SECRET_FILE, 'utf8').trim(), 'hex');
const IDENTITY = (() => {
  const f = path.join(DATA, 'identity.key');
  let j = readJson(f, null);
  if (!j || !j.priv || !j.pub) { const id = sec.genIdentity(); j = { priv: sec.b64u(id.privRaw), pub: sec.b64u(id.pubRaw) }; fs.writeFileSync(f, JSON.stringify(j), { mode: 0o600 }); }
  return j;
})();

function loadUsers() { return readJson(USERS_FILE, {}); }
function hashKey(key, salt) { return crypto.scryptSync(String(key), salt, 32).toString('hex'); }
function addUser(name, key, days, tag) {
  const users = loadUsers();
  const salt = crypto.randomBytes(16).toString('hex');
  users[name.toLowerCase()] = { name, salt, hash: hashKey(key, salt), created: Date.now(), tag: tag || 'user', until: days > 0 ? Date.now() + days * 864e5 : 0 };
  writeJson(USERS_FILE, users);
}
function checkUser(name, key) {
  const u = loadUsers()[String(name || '').toLowerCase()];
  const salt = u ? u.salt : 'x'.repeat(32);
  const h = Buffer.from(hashKey(key || '', salt), 'hex');
  const ok = u && crypto.timingSafeEqual(h, Buffer.from(u.hash, 'hex'));
  if (ok && u.until && u.until < Date.now()) return null;
  return ok ? u : null;
}
function profile(u) { return { name: u.name, tag: u.tag || 'user', until: u.until || 0, created: u.created || 0 }; }
function bindOrCheckHwid(user, hwid) {
  const users = loadUsers();
  const k = user.name.toLowerCase();
  const u = users[k];
  if (!u) return false;
  if (!u.hwid) { u.hwid = hwid; writeJson(USERS_FILE, users); user.hwid = hwid; return true; }
  if (CFG.hwidStrict === false) return true;
  return u.hwid === hwid;
}
function b64u(b) { return Buffer.from(b).toString('base64url'); }
function makeToken(user) {
  const ttlMs = CFG.tokenTtlHours > 0 ? CFG.tokenTtlHours * 3600e3 : CFG.tokenTtlDays * 864e5;
  const body = b64u(JSON.stringify({ u: user.name, exp: Date.now() + ttlMs, tv: user.tv || 0 }));
  return body + '.' + crypto.createHmac('sha256', SECRET).update(body).digest('base64url');
}
function verifyToken(tok) {
  try {
    const [body, sig] = String(tok).split('.');
    const exp = crypto.createHmac('sha256', SECRET).update(body).digest('base64url');
    if (sig.length !== exp.length || !crypto.timingSafeEqual(Buffer.from(sig), Buffer.from(exp))) return null;
    const p = JSON.parse(Buffer.from(body, 'base64url').toString());
    if (p.exp < Date.now()) return null;                 // token itself expired
    const u = loadUsers()[p.u.toLowerCase()];
    if (!u) return null;                                 // user deleted
    if ((u.tv || 0) !== (p.tv || 0)) return null;        // token revoked (token-version bumped)
    if (u.until && u.until < Date.now()) return null;    // subscription expired
    return u;
  } catch { return null; }
}

/* ---------- cosmetics (equipped items live on the host: the host is the source of truth) ---------- */
const COS_FILE = path.join(DATA, 'cosmetics.json');
const COS_CATALOG = (() => {
  // { slots: ['head',..], items: { id: slot } } -- shipped next to relay.js (generated by tools/build-pack.js)
  const c = readJson(path.join(ROOT, 'cosmetics-catalog.json'), readJson(path.join(DATA, 'cosmetics-catalog.json'), { slots: [], items: {} }));
  return { slots: Array.isArray(c.slots) ? c.slots : [], items: c.items && typeof c.items === 'object' ? c.items : {} };
})();
let cosDb = readJson(COS_FILE, {});
let cosTimer = null;
function cosFlush() {
  if (!cosTimer) return;
  clearTimeout(cosTimer); cosTimer = null;
  try { writeJson(COS_FILE, cosDb); } catch (e) { console.error('cosmetics save failed', e.message); }
}
function cosSave() { if (!cosTimer) cosTimer = setTimeout(cosFlush, 400); }
// drop unknown slots/ids and ids that belong to another slot
function cosClean(eq) {
  const out = {};
  if (!eq || typeof eq !== 'object' || Array.isArray(eq)) return out;
  for (const slot of COS_CATALOG.slots) {
    const id = eq[slot];
    if (typeof id === 'string' && Object.prototype.hasOwnProperty.call(COS_CATALOG.items, id) && COS_CATALOG.items[id] === slot) out[slot] = id;
  }
  return out;
}
function cosGet(user) { return cosClean(cosDb[user.name.toLowerCase()]); }
function cosSet(user, eq) { cosDb[user.name.toLowerCase()] = cosClean(eq); cosSave(); return cosDb[user.name.toLowerCase()]; }

/* ---------- logs ---------- */
function logFile(user) { return path.join(DATA, 'logs', user.name.toLowerCase().replace(/[^a-z0-9_.-]/g, '_') + '.jsonl'); }
function appendLog(user, entry) {
  const e = { ts: entry.ts || Date.now(), sev: entry.sev || 'info', tag: String(entry.tag || '').slice(0, 24), msg: String(entry.msg || '').slice(0, 2000) };
  if (entry.clear) { e.clear = true; e.msg = ''; }
  fs.appendFile(logFile(user), JSON.stringify(e) + '\n', () => {});
  return e;
}
function readHistory(user, limit = 300) {
  let txt = '';
  try { txt = fs.readFileSync(logFile(user), 'utf8'); } catch { return []; }
  const lines = txt.split('\n').filter(Boolean);
  const out = [];
  for (const l of lines) {
    try {
      const e = JSON.parse(l);
      if (e.clear) out.length = 0; else out.push(e);
    } catch { /* skip */ }
  }
  return out.slice(-limit);
}
function compactLog(user) {
  try {
    const f = logFile(user);
    if (fs.statSync(f).size < 4 * 1024 * 1024) return;
    const keep = readHistory(user, 2000);
    fs.writeFileSync(f, keep.map(e => JSON.stringify(e)).join('\n') + '\n');
  } catch { /* none */ }
}

/* ---------- sessions ---------- */
const sessions = new Map(); // key: user name lower
const usedPorts = new Set();

function frame(id, data) {
  const h = Buffer.allocUnsafe(4);
  h.writeUInt32BE(id, 0);
  return Buffer.concat([h, data]);
}

function releaseSession(s, why) {
  if (!s || s.released) return;
  s.released = true;
  clearTimeout(s.grace);
  for (const c of s.conns.values()) c.destroy();
  s.conns.clear();
  try { s.listener.close(); } catch { /* ignore */ }
  usedPorts.delete(s.port);
  if (sessions.get(s.key) === s) sessions.delete(s.key);
  const e = appendLog(s.user, { sev: 'info', tag: 'RELAY', msg: 'Address ' + CFG.publicHost + ':' + s.port + ' released (' + why + ')' });
  if (s.ws && s.ws.readyState === 1) sealSend(s.ws, { t: 'log', e });
}

function sendJson(ws, o) { if (ws && ws.readyState === 1) ws.send(JSON.stringify(o)); }

function openSession(user, ws, server, version) {
  const key = user.name.toLowerCase();
  const old = sessions.get(key);
  if (old) releaseSession(old, 'replaced');
  return new Promise((resolve, reject) => {
    const tryPort = (p) => {
      if (p > CFG.portMax) return reject(new Error('no free ports'));
      if (usedPorts.has(p)) return tryPort(p + 1);
      const listener = net.createServer({ noDelay: true });
      listener.once('error', err => { if (err.code === 'EADDRINUSE') tryPort(p + 1); else reject(err); });
      listener.listen(p, '0.0.0.0', () => {
        listener.removeAllListeners('error');
        listener.on('error', () => {});
        usedPorts.add(p);
        const s = { key, user, port: p, server, version, listener, ws, conns: new Map(), nextId: 1, released: false, grace: null };
        sessions.set(key, s);
        listener.on('connection', sock => onPlayer(s, sock));
        resolve(s);
      });
    };
    tryPort(CFG.portMin + Math.floor(Math.random() * (CFG.portMax - CFG.portMin + 1)));
  });
}

function onPlayer(s, sock) {
  sock.setNoDelay(true);
  sock.on('error', () => {});
  const ws = s.ws;
  if (!ws || ws.readyState !== 1 || s.conns.size >= CFG.maxConnsPerSession) { sock.destroy(); return; }
  const id = s.nextId++;
  s.conns.set(id, sock);
  const ip = (sock.remoteAddress || '').replace('::ffff:', '');
  sealSend(ws, { t: 'c_open', id, ip });
  sock.on('data', d => {
    if (ws.readyState !== 1) return;
    ws.send(frame(id, d), { binary: true, compress: false });
    if (ws.bufferedAmount > 6e6) throttle(s);
  });
  sock.on('close', () => {
    if (s.conns.get(id) === sock) { s.conns.delete(id); sealSend(s.ws, { t: 'c_close', id }); }
  });
}

function throttle(s) {
  if (s.throttled) return;
  s.throttled = true;
  for (const c of s.conns.values()) c.pause();
  const iv = setInterval(() => {
    if (!s.ws || s.ws.readyState !== 1 || s.ws.bufferedAmount < 1e6) {
      clearInterval(iv); s.throttled = false;
      for (const c of s.conns.values()) c.resume();
    }
  }, 50);
}

/* ---------- HTTPS + WS ---------- */
const tlsOpts = {
  key: fs.readFileSync(path.join(DATA, 'tls.key')),
  cert: fs.readFileSync(path.join(DATA, 'tls.crt'))
};
const failures = new Map(); // ip -> [timestamps]
function tooMany(ip) {
  const now = Date.now();
  const a = (failures.get(ip) || []).filter(t => now - t < 60000);
  failures.set(ip, a);
  return a.length >= 8;
}

const httpServer = https.createServer(tlsOpts, (req, res) => {
  const ip = (req.socket.remoteAddress || '').replace('::ffff:', '');
  const json = (code, o) => { res.writeHead(code, { 'content-type': 'application/json' }); res.end(JSON.stringify(o)); };
  if (req.method === 'GET' && req.url === '/api/health') return json(200, { ok: true });
  if (req.method === 'POST' && req.url === '/api/login') { return json(410, { error: 'use_secure_ws' }); }
  json(404, { error: 'not_found' });
});

const wss = new WebSocketServer({ noServer: true, perMessageDeflate: false, maxPayload: 16 * 1024 * 1024 });
httpServer.on('upgrade', (req, socket, head) => {
  const u = new URL(req.url, 'http://x');
  if (u.pathname !== '/ws') { socket.destroy(); return; }
  wss.handleUpgrade(req, socket, head, ws => onConn(ws, (req.socket.remoteAddress || '').replace('::ffff:', '')));
});

/* ---------- presence (who is online, who may be labeled) ---------- */
const apps = new Map(); // user key -> ws
let presenceTimer = null;
function schedulePresence() {
  if (presenceTimer) return;
  presenceTimer = setTimeout(() => { presenceTimer = null; broadcastPresence(); }, 150);
}
function broadcastPresence() {
  const live = [...apps.values()].filter(w => w.readyState === 1);
  const users = live.filter(w => w._visible && w._ident && w._ident.nick).map(w => ({
    name: w._user.name, tag: CFG.labelTag, nick: w._ident.nick, server: w._ident.server || '', cos: cosGet(w._user)
  }));
  const payload = { t: 'presence', users, debugAll: !!CFG.debugLabelAll, online: live.length };
  for (const w of live) if (w._visible) sealSend(w, payload);
}

function onConn(ws, ip) {
  ws.isAlive = true;
  ws._ip = ip;
  ws._keys = null;
  ws._user = null;
  ws._authTimer = setTimeout(() => { try { ws.close(4001, 'auth-timeout'); } catch (e) {} }, 8000);
  ws.on('pong', () => { ws.isAlive = true; });
  ws.on('error', () => {});
  ws.on('message', async (data, isBinary) => {
    if (isBinary) { if (ws._user) onTunnelUp(ws, data); return; }
    if (!ws._keys) return doHandshake(ws, data);
    let m;
    try { m = sec.open(ws._keys.rx, data.toString()); } catch (e) { return; }
    if (!ws._user) return doAuth(ws, m);
    return onControl(ws, m);
  });
  ws.on('close', () => onConnClose(ws));
}

function doHandshake(ws, data) {
  let hello;
  try { hello = JSON.parse(data.toString()); } catch (e) { try { ws.close(4002, 'bad-hs'); } catch (e2) {} return; }
  let r;
  try { r = sec.serverAccept(IDENTITY.priv, hello); } catch (e) { try { ws.close(4002, 'bad-hs'); } catch (e2) {} return; }
  ws._keys = { tx: r.tx, rx: r.rx };
  try { ws.send(JSON.stringify(r.reply)); } catch (e) {}
}

function sealSend(ws, o) {
  if (!ws || ws.readyState !== 1 || !ws._keys) return;
  const pad = crypto.randomBytes(1 + (crypto.randomBytes(1)[0] % 40)).toString('base64url');
  try { ws.send(sec.seal(ws._keys.tx, Object.assign({}, o, { _p: pad }))); } catch (e) {}
}

// Tell a client its access ended and disconnect it. Close code 4005 = do not auto-reconnect.
function killApp(ws, reason) {
  if (!ws) return;
  sealSend(ws, { t: 'kill', reason: reason || 'revoked' });
  setTimeout(() => { try { ws.close(4005, String(reason || 'revoked').slice(0, 60)); } catch (e) {} }, 120);
}

function doAuth(ws, m) {
  clearTimeout(ws._authTimer);
  const ip = ws._ip;
  if (!m || m.t !== 'auth') { sealSend(ws, { t: 'authfail', reason: 'proto' }); try { ws.close(4003, 'proto'); } catch (e) {} return; }
  const hwid = typeof m.hwid === 'string' ? m.hwid.slice(0, 128) : '';
  if (!hwid) { sealSend(ws, { t: 'authfail', reason: 'hwid' }); try { ws.close(4003, 'hwid'); } catch (e) {} return; }
  let user = null;
  if (m.mode === 'resume' && m.token) {
    user = verifyToken(m.token);
  } else {
    if (tooMany(ip)) { sealSend(ws, { t: 'authfail', reason: 'rate' }); try { ws.close(4003, 'rate'); } catch (e) {} return; }
    user = checkUser(m.username, m.key);
    if (!user) { failures.get(ip).push(Date.now()); sealSend(ws, { t: 'authfail', reason: 'invalid' }); try { ws.close(4003, 'invalid'); } catch (e) {} return; }
  }
  if (!user) { sealSend(ws, { t: 'authfail', reason: 'invalid' }); try { ws.close(4003, 'invalid'); } catch (e) {} return; }
  if (!bindOrCheckHwid(user, hwid)) {
    appendLog(user, { sev: 'warn', tag: 'AUTH', msg: 'HWID mismatch from ' + ip + ' (login refused)' });
    sealSend(ws, { t: 'authfail', reason: 'hwid' });
    try { ws.close(4003, 'hwid'); } catch (e) {}
    return;
  }
  appendLog(user, { sev: 'info', tag: 'AUTH', msg: 'Signed in from ' + ip });
  attachUser(ws, user);
}

function attachUser(ws, user) {
  const key = user.name.toLowerCase();
  ws._visible = true;
  ws._ident = null;
  ws._user = user;
  const prev = apps.get(key);
  apps.set(key, ws);
  if (prev && prev !== ws) { prev._visible = false; killApp(prev, 'another-device'); } // one active app per account
  schedulePresence();
  compactLog(user);
  sealSend(ws, Object.assign({ t: 'hello', host: CFG.publicHost, versions: CFG.versions || [], protoPatches: PROTO_PATCHES, engineKey: ENGINE_KEY, token: makeToken(user), history: readHistory(user), cosmetics: cosGet(user) }, profile(user)));
  const s = sessions.get(key);
  if (s && !s.released) {
    if (s.ws && s.ws !== ws && s.ws.readyState === 1) { try { s.ws.close(4000, 'replaced'); } catch (e) {} }
    clearTimeout(s.grace);
    s.ws = ws;
    sealSend(ws, { t: 'resumed', address: CFG.publicHost + ':' + s.port, port: s.port, server: s.server, version: s.version });
  }
}

async function onControl(ws, m) {
  const user = ws._user;
  const key = user.name.toLowerCase();
  const cur = sessions.get(key);
    switch (m.t) {
      case 'open': {
        try {
          const ns = await openSession(user, ws, String(m.server || '').slice(0, 200), String(m.version || ''));
          const e = appendLog(user, { sev: 'info', tag: 'RELAY', msg: 'Address ' + CFG.publicHost + ':' + ns.port + ' created for ' + ns.server + ' (' + ns.version + ')' });
          sealSend(ws, { t: 'opened', address: CFG.publicHost + ':' + ns.port, port: ns.port, server: ns.server, version: ns.version });
          sealSend(ws, { t: 'log', e });
        } catch (err) {
          sealSend(ws, { t: 'error', for: 'open', message: String(err.message || err) });
        }
        break;
      }
      case 'close': {
        if (cur && cur.ws === ws) releaseSession(cur, 'closed by user');
        sealSend(ws, { t: 'closed' });
        break;
      }
      case 'log': appendLog(user, m.e || m); break;
      case 'clear': appendLog(user, { clear: true }); break;
      case 'c_close': {
        if (cur && cur.ws === ws) { const sock = cur.conns.get(m.id); if (sock) { cur.conns.delete(m.id); sock.destroy(); } }
        break;
      }
      case 'cosreq': if (COS_ASSETS) sealSend(ws, Object.assign({ t: 'cosassets' }, COS_ASSETS)); break;
      case 'ping': sealSend(ws, { t: 'pong' }); break;
      case 'prefs': ws._visible = m.visible !== false; schedulePresence(); break;
      case 'cosmetics': {
        // client sends the complete equipped map on every change; reply with what was actually stored
        const eq = cosSet(user, m.equipped);
        sealSend(ws, { t: 'cosmetics', equipped: eq, ack: true, seq: Number.isFinite(m.seq) ? m.seq : undefined });
        schedulePresence();
        break;
      }
      case 'ident': {
        const nick = typeof m.nick === 'string' ? m.nick.replace(/[^\w.]/g, '').slice(0, 16) : '';
        ws._ident = nick ? { nick, server: String(m.server || '').slice(0, 200) } : null;
        schedulePresence();
        break;
      }
    }
}

function onTunnelUp(ws, data) {
  const cur = sessions.get(ws._user.name.toLowerCase());
  if (!cur || cur.ws !== ws || data.length < 5) return;
  const sock = cur.conns.get(data.readUInt32BE(0));
  if (sock && !sock.destroyed) sock.write(data.subarray(4));
}

function onConnClose(ws) {
  clearTimeout(ws._authTimer);
  if (!ws._user) return;
  const key = ws._user.name.toLowerCase();
  if (apps.get(key) === ws) apps.delete(key);
  schedulePresence();
  const cur = sessions.get(key);
  if (!cur || cur.ws !== ws) return;
  for (const c of cur.conns.values()) c.destroy();
  cur.conns.clear();
  cur.ws = null;
  appendLog(ws._user, { sev: 'warn', tag: 'RELAY', msg: 'App disconnected; address kept for ' + Math.round(CFG.graceMs / 1000) + 's' });
  cur.grace = setTimeout(() => releaseSession(cur, 'app offline'), CFG.graceMs);
}

setInterval(() => {
  for (const ws of wss.clients) {
    if (!ws.isAlive) { ws.terminate(); continue; }
    ws.isAlive = false;
    try { ws.ping(); } catch { /* ignore */ }
  }
}, 20000);

// Periodic server-side re-validation: kick any logged-in app whose account was deleted,
// expired, or revoked since it connected (without waiting for it to reconnect).
setInterval(() => {
  const users = loadUsers();
  for (const [key, ws] of apps) {
    if (!ws || ws.readyState !== 1) continue;
    const u = users[key];
    let reason = '';
    if (!u) reason = 'deleted';
    else if (u.until && u.until < Date.now()) reason = 'expired';
    else if ((u.tv || 0) !== ((ws._user && ws._user.tv) || 0)) reason = 'revoked';
    if (!reason) continue;
    appendLog(ws._user, { sev: 'warn', tag: 'AUTH', msg: 'Access ' + reason + ' - disconnecting' });
    const s = sessions.get(key);
    if (s) releaseSession(s, reason);
    killApp(ws, reason);
  }
}, CFG.revalidateMs);

